/* World: one mission's simulated infrastructure (hosts, clusters, Docker, Harbor, AWS) plus
 * the network resolver used by curl. Missions build a World in their setup() function. */
(function (IG) {
  "use strict";
  const U = IG.util;

  class World {
    constructor() {
      this.catalog = IG.images.baseCatalog();
      this.features = new Set();
      this.hosts = {};
      this.clusters = {};
      this.kube = { current: null, contexts: {} };
      this.events = [];
      this.httpLog = [];
      this.traffic = [];
      this.bootstrap = false;
      this.bootAge = 3 * 86400e3;
      this.flags = {};
      this.listeners = [];
      this.docker = IG.Docker ? new IG.Docker(this) : null;
      this.harbor = null;
      this.aws = null;
      const b = this.addHost("bastion", {
        publicIp: "198.51.100.20",
        userGroups: ["docker"],
        pkgs: [
          "tree",
          "jq",
          "docker-ce",
          "containerd.io",
          "kubectl",
          "openshift-clients",
          "awscli",
          "harbor-cli",
          "zip",
          "unzip",
        ],
      });
      // the key pair that ~/.ssh/config's IdentityFile points at (servers trust it for the login user)
      const own = { owner: b.user, group: b.primaryGroup(b.user) };
      b.vfs.write(
        b.home + "/.ssh/id_ed25519",
        `-----BEGIN OPENSSH PRIVATE KEY-----\n${(U.b64("openssh-key-v1" + U.hex("bastion-key", 300)).match(/.{1,70}/g) || []).join("\n")}\n-----END OPENSSH PRIVATE KEY-----\n`,
        Object.assign({ mode: 0o600 }, own),
      );
      b.vfs.write(
        b.home + "/.ssh/id_ed25519.pub",
        `ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAI${U.hex("bastion-key", 40)} ${b.user}@corelab-bastion\n`,
        Object.assign({ mode: 0o644 }, own),
      );
    }
    now() {
      return IG.clock.now();
    }
    stamp() {
      return this.bootstrap ? this.now() - this.bootAge : this.now();
    }
    addHost(name, spec = {}) {
      const h = (this.hosts[name] = new IG.Host(name, spec, this));
      const b = this.hosts.bastion;
      // the operator's ~/.ssh/config maps each managed host to its login user (as in real fleets)
      if (b && h !== b && h.sshable) {
        const p = b.home + "/.ssh/config";
        const cur = b.vfs.read(p) || "# Managed hosts (generated by CoreLab provisioning)\n";
        b.vfs.write(
          p,
          cur + `\nHost ${name}\n    HostName ${h.ip}\n    User ${h.user}\n    IdentityFile ~/.ssh/id_ed25519\n`,
          { owner: b.user, group: b.primaryGroup(b.user), mode: 0o600 },
        );
      }
      return h;
    }
    get bastion() {
      return this.hosts.bastion;
    }

    emit(msg, level = "INFO") {
      if (this.bootstrap) return;
      const e = { at: this.now(), level, msg };
      this.events.push(e);
      if (this.events.length > 200) this.events.shift();
      this.listeners.forEach((fn) => fn(e));
    }

    addImage(ref, meta) {
      const p = IG.images.parse(ref);
      const key = p.host ? p.full : p.short;
      this.catalog[key] = Object.assign(
        { ref: key, vulns: { critical: 0, high: 0, medium: 0, low: 0 }, size: "84MB" },
        meta,
      );
      return this.catalog[key];
    }
    lookupImage(ref) {
      const p = IG.images.parse(ref);
      const key = p.host ? p.full : p.short;
      const meta = this.catalog[key] || this.catalog[IG.images.aliases[key]];
      return meta
        ? { meta, key: this.catalog[key] ? key : IG.images.aliases[key], parsed: p }
        : { meta: null, key, parsed: p };
    }
    // Resolve an image for a pull. auths: { host: {username, password} }
    pullImage(ref, auths = {}) {
      const p = IG.images.parse(ref);
      if (this.harbor && p.host === this.harbor.host) return this.harbor.pull(p, auths[p.host]);
      const { meta } = this.lookupImage(ref);
      if (!meta) {
        const repo = (p.host ? p.host + "/" : "docker.io/library/") + p.name;
        if (p.host && !/\.lab\.local$|amazonaws\.com$|quay\.io$|docker\.io$/.test(p.host)) {
          return {
            ok: false,
            reason: "notfound",
            error: `failed to resolve reference "${p.full}": failed to do request: Head "https://${p.host}/v2/${p.name}/manifests/${p.tag}": dial tcp: lookup ${p.host}: no such host`,
          };
        }
        return {
          ok: false,
          reason: "notfound",
          error: `rpc error: code = NotFound desc = failed to pull and unpack image "${p.host ? p.full : "docker.io/library/" + p.short}": failed to resolve reference "${repo}:${p.tag}": ${repo}:${p.tag}: not found`,
        };
      }
      return { ok: true, meta };
    }

    addCluster(cluster) {
      this.clusters[cluster.name] = cluster;
      return cluster;
    }
    context() {
      return this.kube.current ? this.kube.contexts[this.kube.current] : null;
    }
    currentCluster() {
      const c = this.context();
      return c ? this.clusters[c.cluster] : null;
    }
    addContext(name, cluster, namespace = "default", user = "admin", makeCurrent = true) {
      this.kube.contexts[name] = { cluster, namespace, user };
      if (makeCurrent) this.kube.current = name;
    }

    reconcile() {
      for (const c of Object.values(this.clusters)) c.reconcile();
    }

    /* ------------------------------------------------------------- network */
    // from: {kind:'host', host} | {kind:'pod', cluster, ns, pod} | {kind:'container', container}
    http(url, from = { kind: "host", host: "bastion" }, opt = {}) {
      const m = String(url).match(/^(?:(https?):\/\/)?([^/:?#]+)(?::(\d+))?([/?][^#]*)?$/i);
      if (!m) return { error: `curl: (3) URL rejected: Malformed input to a URL function` };
      const scheme = (m[1] || "http").toLowerCase();
      const host = m[2].toLowerCase();
      const port = m[3] ? Number(m[3]) : scheme === "https" ? 443 : 80;
      const path = m[4] || "/";
      const req = { scheme, host, port, path, method: opt.method || "GET" };
      let res = this.route(req, from);
      if (!res) res = { error: `curl: (6) Could not resolve host: ${host}` };
      const rec = {
        url: `${scheme}://${host}${m[3] ? ":" + port : ""}${path}`,
        host,
        port,
        path,
        status: res.status || 0,
        ok: !!res.status && res.status < 400,
        from: from.kind,
        src: from.host, // the host the request was sent from (host shells only)
        ns: from.ns,
        cluster: from.cluster,
        at: this.now(),
        target: res.target || null,
      };
      this.httpLog.push(rec);
      this.traffic.push({ at: this.now(), ok: rec.ok, target: res.target || null, from: from.kind });
      if (this.traffic.length > 40) this.traffic.shift();
      this.emit(
        `${rec.ok ? "HTTP" : "NET"} ${req.method} ${rec.url} → ${res.status || "error"}`,
        rec.ok ? "INFO" : "WARN",
      );
      return res;
    }
    route(req, from) {
      const { host } = req;
      if (from.kind === "pod") {
        const c = this.clusters[from.cluster];
        if (host === "localhost" || host === "127.0.0.1") return c.podSelfHttp(from.pod, req);
        const r = c.inClusterHttp(req, from.ns);
        if (r) return r;
      }
      if (from.kind === "container" && this.docker) {
        const r = this.docker.containerNetHttp(req, from.container);
        if (r) return r;
      }
      for (const c of Object.values(this.clusters)) {
        const r = c.externalHttp(req);
        if (r) return r;
      }
      const src = from.kind === "host" ? this.hosts[from.host] : null;
      const local = src && /^(localhost|127\.0\.0\.1|0\.0\.0\.0)$/.test(host);
      if (
        local &&
        src.name === "bastion" &&
        this.docker &&
        this.features.has("docker") &&
        this.docker.containers.some((c) => c.status === "running" && c.ports.some((p) => p.host === req.port))
      )
        return this.docker.hostHttp(req);
      if (this.aws) {
        const r = this.aws.http(req, from);
        if (r) return r;
      }
      if (this.harbor) {
        const r = this.harbor.http(req);
        if (r) return r;
      }
      const ip = src ? this.hostsFile(src, host) : null;
      const h = local
        ? src
        : Object.values(this.hosts).find((x) => x.name === host || x.ip === host || (ip && x.ip === ip));
      if (h) return this.hostHttp(h, req, src, local);
      if (ip)
        return {
          error: `curl: (28) Failed to connect to ${host} port ${req.port} after 10003 ms: Timeout was reached`,
        };
      return null;
    }
    // HTTP to a Linux host: firewall → listening socket → web server content.
    hostHttp(h, req, src, local) {
      const target = { kind: "host", name: h.name };
      const srcIp = src ? src.ip : "10.244.0.1";
      const block = !local && h !== src && h.firewallBlock(req.port, "tcp", srcIp);
      if (block)
        return {
          error:
            block === "drop"
              ? `curl: (28) Failed to connect to ${req.host} port ${req.port} after 10002 ms: Timeout was reached`
              : `curl: (7) Failed to connect to ${req.host} port ${req.port} after 1 ms: ${block === "unreachable" ? "No route to host" : "Couldn't connect to server"}`,
          target,
        };
      const sock = h
        .sockets()
        .find(
          (s) => s.port === req.port && s.proto.startsWith("tcp") && (local || h === src || !s.addr.startsWith("127.")),
        );
      if (!sock)
        return {
          error: `curl: (7) Failed to connect to ${req.host} port ${req.port} after 0 ms: Couldn't connect to server`,
          target,
        };
      if (sock.svc === "ssh" || sock.svc === "sshd")
        return { error: "curl: (1) Received HTTP/0.9 when not allowed", target };
      const def = IG.linux.SVC[sock.svc] || {};
      if (!def.web && !(h.web && h.web.service === sock.svc))
        return { error: "curl: (52) Empty reply from server", target };
      if (req.scheme === "https")
        return { error: `curl: (35) OpenSSL/3.0.13: error:0A00010B:SSL routines::wrong version number`, target };
      let res;
      if (h.web && h.web.service === sock.svc)
        res = IG.runtime.respond(Object.assign({ kind: "web" }, h.web), req.path); // kind "app" answers /healthz too
      else res = this.docroot(h, sock.svc, req.path);
      const log =
        sock.svc === "nginx"
          ? "/var/log/nginx/access.log"
          : h.os === "rhel"
            ? "/var/log/httpd/access_log"
            : "/var/log/apache2/access.log";
      const n = h.vfs.node(log);
      if (n)
        n.content += `${srcIp} - - [${new Date(this.now()).toUTCString()}] "${req.method} ${req.path} HTTP/1.1" ${res.status} ${res.body.length} "-" "curl/8.5.0"
`;
      return Object.assign({ target }, res);
    }
    docroot(h, svc, path) {
      let root = "/var/www/html",
        index = ["index.html", "index.htm", "index.nginx-debian.html"];
      if (svc === "nginx") {
        const conf = [...h.vfs.walk("/etc/nginx/sites-enabled"), ...h.vfs.walk("/etc/nginx/conf.d")]
          .map((p) => h.vfs.read(p) || "")
          .join("\n");
        const r = conf.match(/^\s*root\s+([^;]+);/m);
        if (r) root = r[1].trim();
        const i = conf.match(/^\s*index\s+([^;]+);/m);
        if (i) index = i[1].trim().split(/\s+/);
      }
      const server = svc === "nginx" ? "nginx/1.24.0 (Ubuntu)" : "Apache/2.4.58 (Ubuntu)";
      const file = IG.VFS.norm(path.split("?")[0], "/");
      let p = root.replace(/\/$/, "") + file;
      if (h.vfs.isDir(p)) {
        const hit = index.map((x) => p.replace(/\/$/, "") + "/" + x).find((x) => h.vfs.isFile(x));
        if (!hit)
          return {
            status: 403,
            server,
            body: `<html>
<head><title>403 Forbidden</title></head>
<body>
<center><h1>403 Forbidden</h1></center>
<hr><center>${server}</center>
</body>
</html>`,
          };
        p = hit;
      }
      if (!h.vfs.isFile(p))
        return {
          status: 404,
          server,
          body: `<html>
<head><title>404 Not Found</title></head>
<body>
<center><h1>404 Not Found</h1></center>
<hr><center>${server}</center>
</body>
</html>`,
        };
      const user = svc === "nginx" || svc === "apache2" ? "www-data" : "apache";
      if (!h.canRead(user, p))
        return {
          status: 403,
          server,
          body: `<html>
<head><title>403 Forbidden</title></head>
<body>
<center><h1>403 Forbidden</h1></center>
<hr><center>${server}</center>
</body>
</html>`,
        };
      return { status: 200, server, body: h.vfs.read(p) };
    }
    // /etc/hosts lookup on a host
    hostsFile(h, name) {
      const txt = h.vfs.read("/etc/hosts") || "";
      for (const line of txt.split("\n")) {
        const parts = line.replace(/#.*/, "").trim().split(/\s+/);
        if (parts.length > 1 && parts.slice(1).includes(name)) return parts[0];
      }
      return null;
    }
    resolveName(name, from) {
      if (from && from.kind === "host" && this.hosts[from.host]) {
        const ip = this.hostsFile(this.hosts[from.host], name);
        if (ip) return ip;
      }
      if (from && from.kind === "pod") {
        const svc = this.clusters[from.cluster].dnsLookup(name, from.ns);
        if (svc) return svc.spec.clusterIP;
      }
      for (const c of Object.values(this.clusters)) {
        const ip = c.externalDns(name);
        if (ip) return ip;
      }
      if (this.harbor && name === this.harbor.host) return "10.0.2.30";
      if (this.aws) {
        const ip = this.aws.dns(name);
        if (ip) return ip;
      }
      if (name === "localhost") return "127.0.0.1";
      const h = Object.values(this.hosts).find((x) => x.name === name);
      if (h) return h.ip;
      return null;
    }
  }

  IG.World = World;
})((globalThis.IG = globalThis.IG || {}));
